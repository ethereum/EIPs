// Compiles ERC-4337 EntryPoint v0.7.0, its SenderCreator and the test contracts
// in MinimalAccount.sol, and writes the Python module `entrypoint_v07.py` that
// `test_entrypoint.py` imports. Run from this directory, after extracting tag
// v0.7.0 of eth-infinitism/account-abstraction here and running `npm install`.
const solc = require('solc'); const fs = require('fs'); const path = require('path');
const AA = 'account-abstraction-0.7.0/contracts';  // tag v0.7.0 of eth-infinitism/account-abstraction
const OUT = process.argv[2] || 'entrypoint_v07.py';
function findImport(p) {
  let f;
  if (p.startsWith('@openzeppelin/')) f = path.join('node_modules', p);
  else if (p.startsWith('@aa/')) f = path.join(AA, p.slice(4));
  else f = p;
  try { return { contents: fs.readFileSync(f, 'utf8') }; } catch (e) { return { error: 'not found ' + p }; }
}
const sources = {
  'core/EntryPoint.sol': { content: fs.readFileSync(AA + '/core/EntryPoint.sol', 'utf8') },
  'core/SenderCreator.sol': { content: fs.readFileSync(AA + '/core/SenderCreator.sol', 'utf8') },
  'extra/MinimalAccount.sol': { content: fs.readFileSync(path.join(__dirname, 'MinimalAccount.sol'), 'utf8') },
};
const input = { language: 'Solidity', sources,
  settings: { optimizer: { enabled: true, runs: 1000000 }, viaIR: true,
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences', 'storageLayout'] } } } };
// resolve relative imports inside core/*.sol against AA dir
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: (p) => {
  if (p.startsWith('core/') || p.startsWith('interfaces/') || p.startsWith('utils/')) return findImport(path.join(AA, p));
  return findImport(p); } }));
const errs = (out.errors || []).filter(e => e.severity === 'error');
if (errs.length) { console.error(errs.map(e => e.formattedMessage).join('\n')); process.exit(1); }
const res = {};
for (const [file, cs] of Object.entries(out.contracts)) for (const [name, c] of Object.entries(cs))
  res[name] = { abi: c.abi, bytecode: c.evm.bytecode.object, deployed: c.evm.deployedBytecode.object,
    immutables: c.evm.deployedBytecode.immutableReferences, storage: (c.storageLayout || {}).storage };
fs.writeFileSync('compiled.json', JSON.stringify(res));
for (const n of ['EntryPoint', 'SenderCreator', 'MinimalAccount', 'Shared']) console.log(n, res[n].deployed.length / 2, 'bytes; immutables', JSON.stringify(res[n].immutables));
console.log('EntryPoint storage:', res.EntryPoint.storage.map(s => s.label + '@' + s.slot).join(', '));

// Each contract has at most one immutable; list the byte offsets of its references.
function offsets(name) {
  const refs = Object.values(res[name].immutables || {});
  if (refs.length !== 1) throw new Error(name + ': expected one immutable, got ' + refs.length);
  return '[' + refs[0].map(r => r.start).sort((a, b) => a - b).join(', ') + ']';
}
function hex(name, code) {
  const lines = code.match(/.{1,96}/g).map(l => '    "' + l + '"');
  return name + ' = bytes.fromhex(\n' + lines.join('\n') + '\n)\n';
}
const py = `"""
Runtime bytecode of ERC-4337 EntryPoint v0.7 and helpers, compiled from
eth-infinitism/account-abstraction tag v0.7.0 (contracts/core/EntryPoint.sol,
contracts/core/SenderCreator.sol) and from the test contracts in
assets/eip-8455/entrypoint/MinimalAccount.sol, with solc 0.8.23, optimizer
enabled (1,000,000 runs), viaIR, as in the repository's hardhat config.
Immutable references are the byte offsets solc reports; the test fills them
with the addresses it deploys to. Generated by assets/eip-8455/entrypoint/compile.js.
"""

${hex('ENTRYPOINT_V07', res.EntryPoint.deployed)}ENTRYPOINT_V07_IMMUTABLES = ${offsets('EntryPoint')}  # senderCreator

${hex('SENDER_CREATOR_V07', res.SenderCreator.deployed)}
${hex('MINIMAL_ACCOUNT', res.MinimalAccount.deployed)}MINIMAL_ACCOUNT_IMMUTABLES = ${offsets('MinimalAccount')}  # entryPoint

${hex('SHARED', res.Shared.deployed)}`;
fs.writeFileSync(OUT, py);
console.log('wrote', OUT);
