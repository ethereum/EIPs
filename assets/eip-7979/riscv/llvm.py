"""Validated EVM to LLVM IR: the optimizing back end that validation
makes possible, for a chain that does not pay for compile time.

Same input as aot.py and the same recovered facts -- every destination
a constant, every instruction at one static stack offset, every
subroutine with known inputs and net effect -- emitted as LLVM IR
instead of RISC-V assembly: a stack slot is an alloca, a subroutine is
a function, a jump is a branch.  mem2reg turns the slots into SSA
values, the inliner removes the calls, and the rest of -O2 does what it
does.  The metering is emitted as in aot.py -- every block's gas
charge, the same sums -- and so are the checks validation cannot
retire, stack overflow and return depth once per call; what the
optimizer makes of them is in README.md.

Width 64 types the twins as i64 on i256 slots -- trunc, operate, zext
-- and leaves the narrowing to the optimizer.  Width 256 is the same
code on i256; 256-bit division takes the AOT's one-limb path and traps
otherwise, since there is no compiler-rt to link.  The output links
against runtime.c exactly as the AOT output does.

Pipeline (see harness.py): opt -O2, llc -O2 -mtriple=riscv64, then the
cross gcc assembles and links.  Compilation itself is not counted:
that is the point of the cell.

Subset and placeholder opcodes as in aot.py.
"""
import sys

from aot import (annotate, block_gas, INFO, TWIN_OF, GAS_LIMIT,
                 JUMP, JUMPI, JUMPDEST, CALLSUB, CALLDEST, RETURNSUB,
                 PUSH0, PUSH32, STOP, RETURN, REVERT, OUTER)

MEM_MAX = (1 << 20) - 32
TRAPS = (("depth", "return stack overflow"), ("ovf", "stack overflow"),
         ("gas", "out of gas"), ("mem", "memory out of range"),
         ("unimp", "unimplemented in AOT subset"))


class Fn:
    """Text of one IR function: SSA numbering, labels, terminator state."""

    def __init__(self, header):
        self.lines = [header + " {"]
        self.k = 0
        self.terminated = True
        self.cur = None                              # current block's label

    def tmp(self):
        self.k += 1
        return f"%t{self.k}"

    def fresh(self, hint):
        self.k += 1
        return f"{hint}{self.k}"

    def emit(self, line):
        self.lines.append("  " + line)
        self.terminated = line.startswith(("br ", "ret ", "unreachable"))

    def op(self, text):
        t = self.tmp()
        self.emit(f"{t} = {text}")
        return t

    def label(self, name):
        self.lines.append(f"{name}:")
        self.terminated = False
        self.cur = name

    def goto(self, name):
        """Fall through to a block unless the current one has ended."""
        if not self.terminated:
            self.emit(f"br label %{name}")

    def text(self):
        return "\n".join(self.lines + ["}", ""])


class TranslateLLVM:
    def __init__(self, code, width):
        assert width in (64, 256)
        self.code, self.width = code, width
        self.n = annotate(code)
        self.gas = block_gas(code, self.n)
        self.fns = []

    # -- module ----------------------------------------------------------

    def translate(self):
        n = self.n
        self.function(OUTER)
        for pc in sorted(p for p in n.offset if self.code[p] == CALLDEST):
            self.function(pc)
        return "\n".join([self.header()] + [f.text() for f in self.fns] +
                         [self.helpers()])

    def header(self):
        lines = ["; generated by llvm.py",
                 "@MEM = external global [1048576 x i8], align 32",
                 "@CALLDATA = external global i8",
                 "@CALLDATA_LEN = external constant i64",
                 "declare void @__rt_return(ptr, i64) noreturn",
                 "declare void @__rt_stop() noreturn",
                 "declare void @__rt_revert() noreturn",
                 "declare void @__rt_trap(ptr) noreturn", ""]
        for name, msg in TRAPS:
            lines.append(f'@.msg_{name} = private constant '
                         f'[{len(msg) + 1} x i8] c"{msg}\\00"')
        return "\n".join(lines) + "\n"

    def ret_type(self, entry):
        """A subroutine returns the gas remaining and its frame."""
        net = self.n.net.get(entry)
        items = 0 if net is None else self.n.inputs[entry] + net
        return "{" + ", ".join(["i64"] + ["i256"] * items) + "}"

    # -- one function per subroutine -------------------------------------

    def function(self, entry):
        n, code = self.n, self.code
        pcs = sorted(pc for pc in n.offset if n.entry[pc] == entry)
        b = n.inputs[entry]
        nslots = b + n.maxh[entry]
        if entry is OUTER:
            f = Fn("define void @evm_entry()")
            first = 0
        else:
            args = "".join(f", i256 %in{j}" for j in range(b))
            f = Fn(f"define internal {self.ret_type(entry)} @F{entry}"
                   f"(i64 %base, i64 %depth, i64 %gas0{args})")
            first = entry
        self.fns.append(f)
        f.label("entry")
        for s in range(nslots):
            f.emit(f"%s{s} = alloca i256")
        f.emit("%gasp = alloca i64")
        if entry is OUTER:
            f.emit(f"store i64 {GAS_LIMIT}, ptr %gasp")
            base, depth = "0", "0"
        else:
            f.emit("store i64 %gas0, ptr %gasp")
            for j in range(b):
                f.emit(f"store i256 %in{j}, ptr %s{j}")
            # the two checks validation cannot retire, once per call
            depth = f.op("add i64 %depth, 1")
            self.check(f, f"icmp ugt i64 {depth}, 1024", "depth")
            self.check(f, f"icmp ugt i64 %base, {1024 - nslots}", "ovf")
            base = "%base"
        f.emit(f"br label %B{first}")
        for pc in pcs:
            op = code[pc]
            if pc in self.gas:                       # block leader
                f.goto(f"B{pc}")
                f.label(f"B{pc}")
                self.gas_check(f, self.gas[pc])
            if op == CALLDEST or pc in n.folded:
                continue
            self.instr(f, pc, op, base, depth)
        if not f.terminated:                         # ran off the end
            f.emit("call void @__rt_stop()")
            f.emit("unreachable")
        for name, _ in TRAPS:
            f.label(f"trap_{name}")
            f.emit(f"call void @__rt_trap(ptr @.msg_{name})")
            f.emit("unreachable")

    def check(self, f, cond, trap):
        c = f.op(cond)
        ok = f.fresh("ok")
        f.emit(f"br i1 {c}, label %trap_{trap}, label %{ok}")
        f.label(ok)

    def gas_check(self, f, amount):
        """Charge a basic block's gas -- the metering a mainnet AOT
        cannot omit, and the optimizer cannot remove."""
        g = f.op("load i64, ptr %gasp")
        g = f.op(f"sub i64 {g}, {amount}")
        f.emit(f"store i64 {g}, ptr %gasp")
        self.check(f, f"icmp slt i64 {g}, 0", "gas")

    # -- instructions ----------------------------------------------------

    def ld(self, f, slot):
        return f.op(f"load i256, ptr %s{slot}")

    def st(self, f, slot, v):
        f.emit(f"store i256 {v}, ptr %s{slot}")

    def instr(self, f, pc, op, base, depth):
        n = self.n
        at = n.inputs[n.entry[pc]] + n.offset[pc]   # one past the top
        if PUSH0 <= op <= PUSH32:
            self.st(f, at, str(n.const[pc]))
        elif 0x80 <= op <= 0x8F:
            self.st(f, at, self.ld(f, at - (op - 0x7F)))
        elif 0x90 <= op <= 0x9F:
            d = op - 0x8F
            a, bd = self.ld(f, at - 1), self.ld(f, at - 1 - d)
            self.st(f, at - 1, bd)
            self.st(f, at - 1 - d, a)
        elif op in (0x50, JUMPDEST):
            pass
        elif op == JUMP:
            f.emit(f"br label %B{self.branch_dest(pc)}")
        elif op == JUMPI:
            c = f.op(f"icmp ne i256 {self.ld(f, at - 2)}, 0")
            f.emit(f"br i1 {c}, label %B{self.branch_dest(pc)}, "
                   f"label %B{pc + 1}")
        elif op == CALLSUB:
            self.call(f, pc, base, depth)
        elif op == RETURNSUB:
            self.ret(f, pc, at)
        elif op == RETURN:
            off = f.op(f"trunc i256 {self.ld(f, at - 1)} to i64")
            ln = f.op(f"trunc i256 {self.ld(f, at - 2)} to i64")
            p = f.op(f"getelementptr i8, ptr @MEM, i64 {off}")
            f.emit(f"call void @__rt_return(ptr {p}, i64 {ln})")
            f.emit("unreachable")
        elif op == REVERT:
            f.emit("call void @__rt_revert()")
            f.emit("unreachable")
        elif op == STOP:
            f.emit("call void @__rt_stop()")
            f.emit("unreachable")
        elif op == 0x36:
            v = f.op("load i64, ptr @CALLDATA_LEN")
            self.st(f, at, f.op(f"zext i64 {v} to i256"))
        else:
            self.alu(f, op, at)

    def branch_dest(self, pc):
        n, code = self.n, self.code
        for back in range(1, 34):                    # the folded PUSH
            if pc - back in n.const and pc - back + \
                    (code[pc - back] - 0x5E) == pc:
                return n.const[pc - back]
        raise AssertionError("unfolded branch in valid code?")

    def call(self, f, pc, base, depth):
        n = self.n
        dest = n.callsite[pc]
        h = n.offset[pc] - 1                         # sans the folded dest
        b = n.inputs[n.entry[pc]]
        i = n.inputs[dest]
        k = b + h - i                                # caller items kept
        assert k >= 0, "call reaches below caller frame: outside subset"
        net = n.net.get(dest)
        args = "".join(f", i256 {self.ld(f, k + j)}" for j in range(i))
        g = f.op("load i64, ptr %gasp")
        cb = base if k == 0 else f.op(f"add i64 {base}, {k}")
        r = f.op(f"call {self.ret_type(dest)} @F{dest}"
                 f"(i64 {cb}, i64 {depth}, i64 {g}{args})")
        if net is None:                              # callee never returns
            f.emit("unreachable")
            return
        g = f.op(f"extractvalue {self.ret_type(dest)} {r}, 0")
        f.emit(f"store i64 {g}, ptr %gasp")
        for j in range(i + net):
            self.st(f, k + j,
                    f.op(f"extractvalue {self.ret_type(dest)} {r}, {j + 1}"))

    def ret(self, f, pc, at):
        entry = self.n.entry[pc]
        ty = self.ret_type(entry)
        v = f.op(f"insertvalue {ty} undef, i64 "
                 f"{f.op('load i64, ptr %gasp')}, 0")
        for j in range(at):                          # the whole frame
            v = f.op(f"insertvalue {ty} {v}, i256 {self.ld(f, j)}, {j + 1}")
        f.emit(f"ret {ty} {v}")

    # -- arithmetic and data ---------------------------------------------

    def alu(self, f, op, at):
        narrow = op in TWIN_OF or op in (0xE0, 0xE1, 0xE2)
        base = TWIN_OF.get(op, op)
        ty = "i64" if narrow else "i256"
        pops = INFO[op][0]
        a = self.ld(f, at - 1)                       # top
        b = self.ld(f, at - 2) if pops == 2 else None
        if narrow:
            a = f.op(f"trunc i256 {a} to i64")
            if b is not None:
                b = f.op(f"trunc i256 {b} to i64")
        if op in (0xE0, 0x35):
            r = f.op(f"call {ty} @cdload{self.width}({ty} {a})")
        elif op in (0xE1, 0x51):
            r = f.op(f"call {ty} @mload{self.width}({ty} {a})")
        elif op in (0xE2, 0x52):
            f.emit(f"call void @mstore{self.width}({ty} {a}, {ty} {b})")
            return
        elif base == 0x01:
            r = f.op(f"add {ty} {a}, {b}")
        elif base == 0x02:
            r = f.op(f"mul {ty} {a}, {b}")
        elif base == 0x03:
            r = f.op(f"sub {ty} {a}, {b}")
        elif base in (0x04, 0x06):
            r = self.divmod(f, base, ty, a, b)
        elif base in (0x10, 0x11, 0x12, 0x13, 0x14):
            pred = {0x10: "ult", 0x11: "ugt", 0x12: "slt", 0x13: "sgt",
                    0x14: "eq"}[base]
            r = f.op(f"icmp {pred} {ty} {a}, {b}")
            r = f.op(f"zext i1 {r} to {ty}")
        elif base == 0x15:
            r = f.op(f"icmp eq {ty} {a}, 0")
            r = f.op(f"zext i1 {r} to {ty}")
        elif base in (0x16, 0x17, 0x18):
            sym = {0x16: "and", 0x17: "or", 0x18: "xor"}[base]
            r = f.op(f"{sym} {ty} {a}, {b}")
        elif base == 0x19:
            r = f.op(f"xor {ty} {a}, -1")
        elif base in (0x1B, 0x1C):                   # shift by top
            sym = "shl" if base == 0x1B else "lshr"
            ok = f.op(f"icmp ult {ty} {a}, {64 if narrow else 256}")
            s = f.op(f"{sym} {ty} {b}, {a}")
            r = f.op(f"select i1 {ok}, {ty} {s}, {ty} 0")
        else:
            raise NotImplementedError(f"opcode {op:#x} in LLVM subset")
        if narrow:
            r = f.op(f"zext i64 {r} to i256")
        self.st(f, at - pops, r)

    def divmod(self, f, base, ty, a, b):
        """EVM division: by zero gives zero.  At 256 bits only the
        one-limb case, as in aot.py; wider operands trap."""
        insn = "udiv" if base == 0x04 else "urem"
        if ty == "i256":
            hi = f.op(f"or i256 {a}, {b}")
            hi = f.op(f"lshr i256 {hi}, 64")
            self.check(f, f"icmp ne i256 {hi}, 0", "unimp")
            a = f.op(f"trunc i256 {a} to i64")
            b = f.op(f"trunc i256 {b} to i64")
        z = f.op(f"icmp eq i64 {b}, 0")
        do, done, pred = f.fresh("div"), f.fresh("divdone"), f.cur
        f.emit(f"br i1 {z}, label %{done}, label %{do}")
        f.label(do)
        q = f.op(f"{insn} i64 {a}, {b}")
        f.emit(f"br label %{done}")
        f.label(done)
        r = f.op(f"phi i64 [ {q}, %{do} ], [ 0, %{pred} ]")
        if ty == "i256":
            r = f.op(f"zext i64 {r} to i256")
        return r

    # -- memory and calldata, as IR functions the inliner may absorb ------

    def helpers(self):
        out = []
        for width in (64, 256):
            out.append(self.h_mload(width))
            out.append(self.h_mstore(width))
            out.append(self.h_cdload(width))
        return "\n".join(out)

    @staticmethod
    def bound(f, off_ty, off):
        """Offset must fit 64 bits and leave room for a 32-byte word,
        as aot.py checks; returns the i64 offset."""
        if off_ty == "i256":
            hi = f.op(f"lshr i256 {off}, 64")
            c = f.op(f"icmp ne i256 {hi}, 0")
            f.emit(f"br i1 {c}, label %trap, label %fits")
            f.label("fits")
            off = f.op(f"trunc i256 {off} to i64")
        c = f.op(f"icmp ugt i64 {off}, {MEM_MAX}")
        f.emit(f"br i1 {c}, label %trap, label %go")
        f.label("go")
        return off

    def h_mload(self, width):
        ty = f"i{width}"
        f = Fn(f"define internal {ty} @mload{width}({ty} %off)")
        f.label("entry")
        off = self.bound(f, ty, "%off")
        lo = 32 - width // 8                         # first byte of the value
        acc = "0"
        for i in range(width // 8):
            p = f.op(f"getelementptr i8, ptr @MEM, i64 "
                     f"{f.op(f'add i64 {off}, {lo + i}')}")
            v = f.op(f"load i8, ptr {p}")
            v = f.op(f"zext i8 {v} to {ty}")
            sh = width - 8 * (i + 1)
            if sh:
                v = f.op(f"shl {ty} {v}, {sh}")
            acc = f.op(f"or {ty} {acc}, {v}")
        f.emit(f"ret {ty} {acc}")
        f.label("trap")
        f.emit("call void @__rt_trap(ptr @.msg_mem)")
        f.emit("unreachable")
        return f.text()

    def h_mstore(self, width):
        ty = f"i{width}"
        f = Fn(f"define internal void @mstore{width}({ty} %off, {ty} %v)")
        f.label("entry")
        off = self.bound(f, ty, "%off")
        for i in range(32):                          # the whole word
            p = f.op(f"getelementptr i8, ptr @MEM, i64 "
                     f"{f.op(f'add i64 {off}, {i}')}")
            sh = 8 * (31 - i)
            if sh >= width:
                f.emit(f"store i8 0, ptr {p}")
                continue
            v = f.op(f"lshr {ty} %v, {sh}") if sh else "%v"
            v = f.op(f"trunc {ty} {v} to i8")
            f.emit(f"store i8 {v}, ptr {p}")
        f.emit("ret void")
        f.label("trap")
        f.emit("call void @__rt_trap(ptr @.msg_mem)")
        f.emit("unreachable")
        return f.text()

    def h_cdload(self, width):
        """Bytes past the end of calldata read as zero; an index past
        2^64 reads all zero (aot.py's `far` path)."""
        ty = f"i{width}"
        f = Fn(f"define internal {ty} @cdload{width}({ty} %idx)")
        f.label("entry")
        idx = "%idx"
        if width == 256:
            hi = f.op("lshr i256 %idx, 64")
            c = f.op(f"icmp ne i256 {hi}, 0")
            f.emit("br i1 %s, label %%far, label %%near" % c)
            f.label("near")
            idx = f.op("trunc i256 %idx to i64")
        ln = f.op("load i64, ptr @CALLDATA_LEN")
        lo = 32 - width // 8
        acc = "0"
        for i in range(width // 8):
            at = f.op(f"add i64 {idx}, {lo + i}")
            c = f.op(f"icmp ult i64 {at}, {ln}")
            inb, nxt, here = f.fresh("in"), f.fresh("next"), f.cur
            f.emit(f"br i1 {c}, label %{inb}, label %{nxt}")
            f.label(inb)
            p = f.op(f"getelementptr i8, ptr @CALLDATA, i64 {at}")
            v = f.op(f"load i8, ptr {p}")
            v = f.op(f"zext i8 {v} to {ty}")
            f.emit(f"br label %{nxt}")
            f.label(nxt)
            v = f.op(f"phi {ty} [ {v}, %{inb} ], [ 0, %{here} ]")
            sh = width - 8 * (i + 1)
            if sh:
                v = f.op(f"shl {ty} {v}, {sh}")
            acc = f.op(f"or {ty} {acc}, {v}")
        f.emit(f"ret {ty} {acc}")
        if width == 256:
            f.label("far")
            f.emit("ret i256 0")
        return f.text()


def translate_llvm(code, width):
    return TranslateLLVM(code, width).translate()


